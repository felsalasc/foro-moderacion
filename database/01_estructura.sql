-- Ejecutar una vez en el esquema propio de foro-moderacion, sin tablas previas.
-- No modifica datos ni tablas de usuarios o contenido.
CREATE TABLE DECISIONES_MODERACION (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_RECURSO VARCHAR2(10 CHAR) NOT NULL,
    RECURSO_ID NUMBER(19) NOT NULL,
    BANEADO NUMBER(1) NOT NULL,
    MOTIVO VARCHAR2(500 CHAR) NOT NULL,
    ADMINISTRADOR_ID NUMBER(19) NOT NULL,
    FECHA_DECISION TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT UK_DECISION_RECURSO UNIQUE (TIPO_RECURSO, RECURSO_ID),
    CONSTRAINT CK_DECISION_TIPO CHECK (TIPO_RECURSO IN ('TEMA','COMENTARIO')),
    CONSTRAINT CK_DECISION_RECURSO CHECK (RECURSO_ID > 0),
    CONSTRAINT CK_DECISION_ADMIN CHECK (ADMINISTRADOR_ID > 0),
    CONSTRAINT CK_DECISION_BANEADO CHECK (BANEADO IN (0,1))
);
